def ts(t, srt=True):
    h = int(t // 3600)
    m = int(t % 3600 // 60)
    s = t % 60
    return f'{h:02d}:{m:02d}:{s:06.3f}'.replace('.', ',') if srt else f'{m:02d}:{s:06.3f}'


def describe(s):
    if s['kind'] == 'stock':
        u = USAGE.get(s['id'], {})
        return f"Pixabay #{u.get('pixabay_id')} ({u.get('tags', '')[:60]})"
    if s['kind'] == 'photo' and not s.get('comp'):
        return f"Photo {s.get('imgFile')}"
    return f"{s.get('comp')} ({s['kind']})"


def overlay(s):
    ov = s.get('ov')
    if not ov:
        return ''
    parts = [ov.get(k) for k in ('text', 'value', 'label', 'title', 'sub', 'name', 'role', 'line') if ov.get(k)]
    if ov.get('lines'):
        parts += ov['lines']
    if ov.get('items'):
        parts += ov['items']
    return f"[{ov['t']}] " + ' | '.join(str(x) for x in parts)


def scene_plan():
    with open(f'{ROOT}/metadata/scene_plan.csv', 'w', newline='') as fh:
        w = csv.writer(fh)
        w.writerow(['shot', 'start', 'end', 'duration_s', 'category', 'anchor_phrase_spoken', 'english_meaning', 'visual', 'overlay_text', 'transition_in'])
        for s in TL:
            cat = {'stock': 'real footage', 'photo': 'real photograph', 'doc': 'real document', 'mg': 'motion graphics', '3d': '3D'}[s['kind']]
            w.writerow([s['id'], ts(s['start'], False), ts(s['end'], False), s['dur'], cat, (s.get('anchor') or '').replace(' [tail]', ' (cont.)'),
                        s.get('en', ''), describe(s), overlay(s), s.get('trans')])


