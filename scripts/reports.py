def srt():
    """Condensed English translation, one cue per narrative beat (split on sentence breaks)."""
    beats = []
    for s in TL:
        if s.get('anchor', '').endswith('[tail]'):
            continue
        if beats and beats[-1]['en'] == s.get('en'):
            beats[-1]['end'] = s['end']
            continue
        beats.append(dict(start=s['start'], end=s['end'], en=s.get('en') or ''))
    # extend to next beat start and merge empties
    cues = []
    for i, b in enumerate(beats):
        end = beats[i + 1]['start'] if i + 1 < len(beats) else b['end']
        text = b['en'].strip()
        if not text:
            if cues:
                cues[-1][1] = end
            continue
        parts = [x.strip() for x in re.split(r'(?<=[.?!])\s+', text) if x.strip()]
        n = len(parts)
        span = end - b['start']
        tot = sum(len(x) for x in parts)
        t = b['start']
        for x in parts:
            d = span * len(x) / tot
            cues.append([t, t + d, x])
            t += d
    with open(f'{ROOT}/metadata/narration_timestamps.srt', 'w') as fh:
        for i, (a, b, x) in enumerate(cues, 1):
            # wrap ~42 chars per line
            words, lines, cur = x.split(), [], ''
            for w_ in words:
                if len(cur) + len(w_) + 1 > 42:
                    lines.append(cur)
                    cur = w_
                else:
                    cur = (cur + ' ' + w_).strip()
            lines.append(cur)
            fh.write(f"{i}\n{ts(a)} --> {ts(max(a + 0.5, b - 0.04))}\n" + '\n'.join(lines) + '\n\n')
    return len(cues)


